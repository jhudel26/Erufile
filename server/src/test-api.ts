async function createSamplePdf(text: string, filename: string): Promise<string> {
  const doc = await PDFDocument.create();
  const page = doc.addPage([600, 400]);
  const font = await doc.embedFont(StandardFonts.HelveticaBold);
  page.drawText(text, { x: 50, y: 300, size: 24, font, color: rgb(0.9, 0.1, 0.1) });
  page.drawText('Generated by EruFile Test Suite', { x: 50, y: 250, size: 14, color: rgb(0.3, 0.3, 0.3) });
  const bytes = await doc.save();
  const tmpPath = path.join(process.cwd(), filename);
  fs.writeFileSync(tmpPath, bytes);
  return tmpPath;
}

